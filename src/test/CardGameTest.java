import org.junit.jupiter.api.*;
import static org.junit.jupiter.api.Assertions.*;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.List;

public class CardGameTest {
    private static final int DEFAULT_NUM_PLAYERS = 4;

    private CardGame game;
    private Path tempPackFile;

    /**
     * Sets up a temporary pack file before each test to ensure isolation and avoid side effects.
     * Initializes the CardGame instance with the temporary pack file.
     * Used for testing valid pack file scenarios.
     * 
     * @throws IOException
     */
    @BeforeEach
    public void setUp() throws IOException {
        int requiredCardCount = DEFAULT_NUM_PLAYERS * 8;
        java.util.List<String> list = new java.util.ArrayList<>();
        for (int i = 0; i < requiredCardCount; i++) {
            // Create a pack with values from 1 to requiredCardCount
            list.add(String.valueOf(i + 1));
        }
        tempPackFile = createTempPackFile(list);

        List<Integer> validPack = CardGame.loadAndValidatePack(tempPackFile.toString(), DEFAULT_NUM_PLAYERS);
        
        game = new CardGame(DEFAULT_NUM_PLAYERS, validPack);
    }

    /**
     * Cleans up any temporary files created during the tests.
     * 
     * @throws IOException
     */
    @AfterEach
    public void tearDown() throws IOException {
        // Delete the temporary pack file after each test to avoid clutter
        if (Files.exists(tempPackFile)) {
            Files.delete(tempPackFile);
        }
        //  Clean up any output files generated by the game during tests
        if (game != null) {
            int n = game.getNumPlayers(); 
            for (int i = 1; i <= n; i++) {
                // Limpiar output de jugadores
                File playerOutput = new File("player" + i + "_output.txt");
                if (playerOutput.exists()) {
                    playerOutput.delete();
                }
                
                // Limpiar output de mazos (decks)
                File deckOutput = new File("deck" + i + "_output.txt");
                if (deckOutput.exists()) {
                    deckOutput.delete();
                }
            }
        }
    }

    /**
     * Tests the loading of a valid pack file.
     * Ensures that the number of players and decks is correctly initialized.
     */
    @Test
    public void testLoadValidPackFile() {
        assertNotNull(game, "The CardGame instance should not be null after loading a valid pack file.");
        
        assertEquals(DEFAULT_NUM_PLAYERS, game.getNumPlayers(), "The number of players must match the default value.");
        assertEquals(DEFAULT_NUM_PLAYERS, game.getDecks().size(), "There must be a deck for each player.");
    }

    /**
     * Tests the loading of an invalid pack file with an invalid number of cards.
     * 
     * @throws IOException
     */
    @Test
    public void testRejectPackWithInvalidCardCount() throws IOException {
        int expectedCardCount = DEFAULT_NUM_PLAYERS * 8; 

        // 1. 3 cards
        Path threeCardFile = createTempPackFile(List.of("1", "2", "3"));
        assertNull(CardGame.loadAndValidatePack(threeCardFile.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for invalid card count (3) in the pack file.");
        Files.deleteIfExists(threeCardFile);

        // 2. 31 cards (n-1)
        Path fileOneLess = createTempPackFile(Collections.nCopies(expectedCardCount - 1, "1"));
        assertNull(CardGame.loadAndValidatePack(fileOneLess.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for invalid card count (n-1) in the pack file.");
        Files.deleteIfExists(fileOneLess);

        // 3. 33 cards (n+1)
        Path fileOneMore = createTempPackFile(Collections.nCopies(expectedCardCount + 1, "1"));
        assertNull(CardGame.loadAndValidatePack(fileOneMore.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for invalid card count (n+1) in the pack file.");
        Files.deleteIfExists(fileOneMore);
    }

    /**
     * Tests the loading of an invalid pack file containing empty rows.
     * Empty rows are skipped, meaning the pack will not meet the 8*n requirement.
     * 
     * @throws IOException
     */
    @Test
    public void testRejectPackContainingEmptyLines() throws IOException {
        int expectedCardCount = DEFAULT_NUM_PLAYERS * 8; 
        
        // Create a pack with empty lines mixed in. The validator skips them, resulting in insufficient cards.
        List<String> linesWithEmpty = new java.util.ArrayList<>(Collections.nCopies(expectedCardCount, "1"));
        linesWithEmpty.set(2, ""); // Replace valid card with empty string
        
        Path emptyLineFile = createTempPackFile(linesWithEmpty);

        assertNull(CardGame.loadAndValidatePack(emptyLineFile.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for a pack file that falls short of 8n due to empty lines.");

        Files.deleteIfExists(emptyLineFile);
    }

    /**
     * Tests the loading of an invalid pack file containing negative card values.
     * 
     * @throws IOException
     */
    @Test
    public void testRejectPackWithNegativeValues() throws IOException {
        int cardCount = DEFAULT_NUM_PLAYERS * 8;
        // Create a pack with valid count but with a negative value
        List<String> linesWithNegative = Collections.nCopies(cardCount, "1");
        List<String> mutableLines = new java.util.ArrayList<>(linesWithNegative);
        mutableLines.set(5, "-1");
        Path negativeFile = createTempPackFile(mutableLines);

        assertNull(CardGame.loadAndValidatePack(negativeFile.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for negative card values in the pack file.");

        Files.deleteIfExists(negativeFile);
    }

    /**
     * Tests the loading of an invalid pack file containing non-integer card values.
     * 
     * @throws IOException
     */
    @Test
    public void testRejectPackWithNonIntegerValues() throws IOException {
        int cardCount = DEFAULT_NUM_PLAYERS * 8;
        // Create a pack with valid count but with a non-integer value
        List<String> linesWithNonInteger = Collections.nCopies(cardCount, "1");
        List<String> mutableLines = new java.util.ArrayList<>(linesWithNonInteger);
        mutableLines.set(3, "abc");
        Path nonIntegerFile = createTempPackFile(mutableLines);

        assertNull(CardGame.loadAndValidatePack(nonIntegerFile.toString(), DEFAULT_NUM_PLAYERS), 
            "Expected null for non-integer card values in the pack file.");

        Files.deleteIfExists(nonIntegerFile);
    }

    /**
     * Tests the round-robin distribution of cards to players and decks at the start of the game.
     * Ensures that each player and deck receives the correct number of cards and in the correct order.
     */
    @Test
    public void testInitialCardDistribution() {
        int cardCount = DEFAULT_NUM_PLAYERS * 8; // Total cards in the pack
        int expectedCardsPerPlayer = 4;          // Each player should receive 4 cards
        int expectedCardsPerDeck = 4;            // The pack has 8n cards, leaving exactly 4n cards to distribute among n decks (4 cards per deck).

        // Execute the card distribution action
        game.distributeCards();

        // 1. Validate players' hands (Quantity and Round-Robin order)
        for (Player player : game.getPlayers()) {
            List<Card> hand = player.getHand();
            int playerId = player.getPlayerID();

            // Check invariant: each player must hold exactly four cards after distribution
            assertEquals(expectedCardsPerPlayer, hand.size(), 
                "Player " + playerId + " did not receive exactly 4 cards.");

            // Verify round-robin dealing:
            // Since the test pack has sequential values (1, 2, 3...), player 'i' should receive cards at positions: i, i+n, i+2n, i+3n.
            for (int round = 0; round < expectedCardsPerPlayer; round++) {
                int expectedCardValue = playerId + (round * DEFAULT_NUM_PLAYERS);
                assertEquals(expectedCardValue, hand.get(round).getValue(),
                    "Player " + playerId + " did not receive the correct card in round " + (round + 1) + ". Round-robin distribution failed.");
            }
        }

        // 2. Validate the contents of the decks (Quantity, FIFO behavior, and Round-Robin order)
        int cardsDealtToPlayers = expectedCardsPerPlayer * DEFAULT_NUM_PLAYERS; 
        
        for (CardDeck deck : game.getDecks()) {
            int deckId = deck.getId();

            // The remaining cards are distributed to the decks.
            for (int round = 0; round < expectedCardsPerDeck; round++) {
                // Drawing cards tests the deck's FIFO invariant simultaneously
                Card drawn = deck.drawCard();
                assertNotNull(drawn, "Deck " + deckId + " received fewer than 4 cards.");
                
                int expectedCardValue = cardsDealtToPlayers + deckId + (round * DEFAULT_NUM_PLAYERS);
                assertEquals(expectedCardValue, drawn.getValue(),
                    "Deck " + deckId + " did not receive the correct card in round " + (round + 1) + ". Round-robin distribution failed.");
            }
        }
    }

    /**
     * Tests that the output logs for players and decks are generated after the game simulation.
     * 
     * @throws InterruptedException
     */
      
    @Test
    public void testOutputLogsAreGenerated() throws InterruptedException, IOException {
        // 1. Create a specific pack that allows winning.
        // Simulate a 4-player pack (32 cards) where Player 1
        // receives four "1" cards in the initial round-robin deal.
        List<String> winningPackList = new java.util.ArrayList<>();
        for(int i = 0; i < 4; i++) {
            winningPackList.add("1"); // Player 1
            winningPackList.add("2"); // Player 2
            winningPackList.add("3"); // Player 3
            winningPackList.add("4"); // Player 4
        }
        for(int i = 0; i < 16; i++) {
            winningPackList.add("5"); // Filler cards for the decks
        }

        Path winningPackPath = createTempPackFile(winningPackList);
        List<Integer> winningPack = CardGame.loadAndValidatePack(winningPackPath.toString(), DEFAULT_NUM_PLAYERS);
        
        // 2. Initialize the game with the prepared pack
        CardGame winGame = new CardGame(DEFAULT_NUM_PLAYERS, winningPack);

        // 3. DISTRIBUTE CARDS BEFORE starting the threads
        winGame.distributeCards();

        // 4. Start the game (Player 1 will declare victory and threads will terminate)
        winGame.startGame();

        // Verify the generation of output logs
        for (int i = 1; i <= DEFAULT_NUM_PLAYERS; i++) {
            Path playerOutput = Path.of("player" + i + "_output.txt");
            Path deckOutput = Path.of("deck" + i + "_output.txt");

            assertTrue(Files.exists(playerOutput), "The output file for player " + i + " was not generated.");
            assertTrue(Files.exists(deckOutput), "The output file for deck " + i + " was not generated.");
        }
        
        Files.deleteIfExists(winningPackPath);
    }

    /**
     * Helper method to create a temporary pack file with specified card values.
     * 
     * @param cardValues
     * @return
     * @throws IOException
     */
    private Path createTempPackFile(List<String> cardValues) throws IOException {
        Path tempFile = Files.createTempFile("temp_pack", ".txt");
        Files.write(tempFile, cardValues);
        return tempFile;
    }
}